CREATE OR REPLACE TABLE CURATED_LAYER.APPOINTMENTS_EXCEPTION AS
SELECT DISTINCT 
    APPT_ID,
    APPT_DATE,
    PATIENT_ID,
    DOCTOR_ID,
    DOCTOR_NAME,
    DEPARTMENT,
    SLOT,
    STATUS,
    CASE
        WHEN PATIENT_ID IS NULL AND DOCTOR_ID IS NULL THEN 'INVALID PATIENT_ID & DOCTOR_ID'
        WHEN PATIENT_ID IS NULL THEN 'INVALID PATIENT_ID'
        WHEN DOCTOR_ID IS NULL THEN 'INVALID DOCTOR_ID'
    END AS ERROR_REASON
FROM STAGE_LAYER.APPOINTMENTS_RAW
WHERE PATIENT_ID IS NULL 
   OR DOCTOR_ID IS NULL;

