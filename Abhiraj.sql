SELECT 
    p.PATIENT_ID,
    p.FULL_NAME,
    COUNT(DISTINCT a.APPT_ID) AS TOTAL_VISITS,
    MAX(a.APPT_DATE) AS LAST_VISITED_DATE,
    SUM(b.NET_AMOUNT) AS LIFE_TIME_REVENUE
FROM CURATED_LAYER.DIM_PATIENT p
LEFT JOIN CURATED_LAYER.FACT_APPOINTMENT a 
    ON p.PATIENT_ID = a.PATIENT_ID
LEFT JOIN CURATED_LAYER.FACT_BILLING b 
    ON p.PATIENT_ID = b.PATIENT_ID
GROUP BY 
    p.PATIENT_ID,
    p.FULL_NAME;

