-- Use Case 1: Department Performance (Sankalp)
-- Shows total, completed, no-show & completion rate
CREATE OR REPLACE VIEW ANALYTICS_LAYER.VW_DEPT_APPT_SUMMARY AS
SELECT D.DEPARTMENT,
    COUNT(*) AS TOTAL_APPOINTMENTS,
    SUM(CASE WHEN F.STATUS='Completed' THEN 1 ELSE 0 END) AS COMPLETED,
    SUM(CASE WHEN F.STATUS='No-Show' THEN 1 ELSE 0 END) AS NO_SHOW,
    ROUND(SUM(CASE WHEN F.STATUS='Completed' THEN 1 ELSE 0 END)*100.0/COUNT(*),2) AS COMPLETION_RATE
FROM CURATED_LAYER.FACT_APPOINTMENT F
JOIN CURATED_LAYER.DIM_DOCTOR D
ON F.DOCTOR_ID = D.DOCTOR_ID
GROUP BY D.DEPARTMENT;

-- Use Case 2: Daily OPD Trend (Akash)
CREATE OR REPLACE VIEW ANALYTICS_LAYER.VW_DAILY_OPD AS
SELECT APPT_DATE,
    COUNT(*) AS DAILY_VISITS,
    SUM(CASE WHEN STATUS = 'No-Show' THEN 1 ELSE 0 END) AS NO_SHOWS,
    ROUND(COUNT(*) * 1.0 / COUNT(DISTINCT DOCTOR_ID), 2) AS AVG_APPTS_PER_DOCTOR
FROM CURATED_LAYER.FACT_APPOINTMENT
GROUP BY APPT_DATE;

-- Use Case 3: Revenue by Department (Utkarsh)
CREATE OR REPLACE VIEW ANALYTICS_LAYER.VW_REVENUE_BY_DEPT AS
SELECT DEPARTMENT,
    SUM(GROSS_AMOUNT) AS TOTAL_GROSS_REVENUE,
    SUM(NET_AMOUNT) AS TOTAL_NET_REVENUE,
    AVG(NET_AMOUNT) AS AVG_BILL_VALUE
FROM CURATED_LAYER.FACT_BILLING
GROUP BY DEPARTMENT;

-- Use Case 4: Patient Utilization (Abhiraj)
CREATE OR REPLACE VIEW ANALYTICS_LAYER.VW_PATIENT_UTILIZATION AS
SELECT p.PATIENT_ID,
    p.FULL_NAME,
    COUNT(DISTINCT a.APPT_ID) AS TOTAL_VISITS,
    MAX(a.APPT_DATE) AS LAST_VISITED_DATE,
    SUM(b.NET_AMOUNT) AS LIFE_TIME_REVENUE
FROM CURATED_LAYER.DIM_PATIENT p
LEFT JOIN CURATED_LAYER.FACT_APPOINTMENT a ON p.PATIENT_ID = a.PATIENT_ID
LEFT JOIN CURATED_LAYER.FACT_BILLING b ON p.PATIENT_ID = b.PATIENT_ID
GROUP BY p.PATIENT_ID, p.FULL_NAME;

-- Use Case 5: Revenue by Payment Type (Anshika)
CREATE OR REPLACE VIEW ANALYTICS_LAYER.VW_REVENUE_BY_PAYMENT_TYPE AS
SELECT 
    CASE WHEN INSURER_NAME = 'SELF' THEN 'SELF' ELSE 'INSURANCE' END AS PAYMENT_TYPE,
    SUM(NET_AMOUNT) AS TOTAL_REVENUE
FROM CURATED_LAYER.FACT_BILLING
GROUP BY CASE WHEN INSURER_NAME = 'SELF' THEN 'SELF' ELSE 'INSURANCE' END;