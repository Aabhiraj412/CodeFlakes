-- Function to validate billing records
CREATE OR REPLACE FUNCTION IS_VALID_BILLING(
    PATIENT_ID STRING,
    BILL_DATE STRING,
    NET_AMOUNT STRING,
    PAYMENT_MODE STRING
)
RETURNS BOOLEAN
LANGUAGE SQL
AS
$$
    CASE
        WHEN PATIENT_ID IS NULL THEN FALSE
        WHEN COALESCE(
            TRY_TO_DATE(BILL_DATE, 'YYYY-MM-DD'),
            TRY_TO_DATE(BILL_DATE, 'DD/MM/YYYY')
        ) IS NULL THEN FALSE
        WHEN TRY_TO_NUMBER(NET_AMOUNT) IS NULL THEN FALSE
        WHEN TRY_TO_NUMBER(NET_AMOUNT) < 0 THEN FALSE
        WHEN PAYMENT_MODE IS NULL THEN FALSE
        ELSE TRUE
    END
$$;

-- Store invalid billing records
INSERT INTO CURATED_LAYER.BILLING_EXCEPTION
SELECT DISTINCT
    *,
    CASE
        WHEN PATIENT_ID IS NULL THEN 'PATIENT_ID NULL'
        WHEN TRY_TO_NUMBER(NET_AMOUNT) < 0 THEN 'NEGATIVE NET_AMOUNT'
        ELSE 'UNKNOWN ERROR'
    END AS ERROR_MSG
FROM STAGE_LAYER.BILLING_RAW
WHERE NOT IS_VALID_BILLING(PATIENT_ID, BILL_DATE, NET_AMOUNT, PAYMENT_MODE);

-- Clean billing data
CREATE OR REPLACE TABLE CURATED_LAYER.CLEAN_BILLING AS
SELECT DISTINCT
    BILL_ID,
    COALESCE(
        TRY_TO_DATE(BILL_DATE, 'YYYY-MM-DD'),
        TRY_TO_DATE(BILL_DATE, 'DD/MM/YYYY')
    ) AS BILL_DATE,
    PATIENT_ID,
    TRIM(SERVICE_CODE),
    INITCAP(TRIM(SERVICE_DESC)),
    UPPER(TRIM(DEPARTMENT)),
    TRY_TO_NUMBER(GROSS_AMOUNT),
    TRY_TO_NUMBER(DISCOUNT_AMOUNT),
    TRY_TO_NUMBER(TAX_AMOUNT),
    GREATEST(TRY_TO_NUMBER(NET_AMOUNT), 0), -- Prevent negative
    UPPER(TRIM(PAYMENT_MODE)),
    COALESCE(TRIM(INSURER_NAME), 'SELF')
FROM STAGE_LAYER.BILLING_RAW
WHERE IS_VALID_BILLING(PATIENT_ID, BILL_DATE, NET_AMOUNT, PAYMENT_MODE);

