USE SCHEMA CURATED_LAYER;

-- Capture invalid patient records
CREATE OR REPLACE TABLE CURATED_LAYER.PATIENTS_EXCEPTION AS
SELECT
    PATIENT_ID,
    FULL_NAME,
    DOB,
    GENDER,
    PHONE,
    EMAIL,
    CITY,
    STATE,
    REGISTRATION_DATE,
    CASE
        WHEN PATIENT_ID IS NULL THEN 'INVALID PATIENT_ID'
        WHEN DOB IS NULL THEN 'NO DOB'
        WHEN PHONE IS NULL OR LENGTH(PHONE) < 10 THEN 'INVALID PHONE' 
    END AS ERROR_REASON
FROM STAGE_LAYER.PATIENTS_RAW
WHERE 
    PATIENT_ID IS NULL
    OR DOB IS NULL
    OR PHONE IS NULL
    OR LENGTH(PHONE) < 10;    

-- Clean & standardize patient data
CREATE OR REPLACE TABLE CURATED_LAYER.CLEAN_PATIENTS AS
SELECT
    PATIENT_ID,
    FULL_NAME,
    DOB,
    GENDER,
    PHONE,
    EMAIL,
    CITY,
    STATE,
    REG_DATE
FROM (
    SELECT
        PATIENT_ID,
        TRIM(FULL_NAME) AS FULL_NAME, -- Remove extra spaces

        -- Validate & standardize DOB
        CASE 
            WHEN DOB IS NULL THEN 'NO DOB'
            WHEN COALESCE(
                    TRY_TO_DATE(DOB),
                    TRY_TO_DATE(REPLACE(DOB, '/', '-'))
                 ) IS NULL 
            THEN 'INVALID'
            ELSE TO_CHAR(
                    COALESCE(
                        TRY_TO_DATE(DOB),
                        TRY_TO_DATE(REPLACE(DOB, '/', '-'))
                    )
                 )
        END AS DOB,

        UPPER(TRIM(GENDER)) AS GENDER, -- Normalize gender

        -- Validate phone
        CASE 
            WHEN PHONE IS NULL OR LENGTH(PHONE) < 10 THEN 'INVALID'
            ELSE PHONE
        END AS PHONE,

        -- Clean email
        LOWER(REPLACE(TRIM(COALESCE(EMAIL, 'NA')), '[AT]', '@')) AS EMAIL,

        UPPER(TRIM(CITY)) AS CITY,
        UPPER(TRIM(STATE)) AS STATE,

        -- Clean registration date
        COALESCE(
            TRY_TO_DATE(REGISTRATION_DATE),
            TRY_TO_DATE(REPLACE(REGISTRATION_DATE, '/', '-'))
        ) AS REG_DATE,

        -- Deduplicate
        ROW_NUMBER() OVER (PARTITION BY PATIENT_ID ORDER BY PATIENT_ID) AS RN
    FROM STAGE_LAYER.PATIENTS_RAW
) t
WHERE RN = 1;

