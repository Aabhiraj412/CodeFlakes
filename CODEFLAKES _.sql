-- GOVERNANCE (Masking)
-- ================================================

-- Mask phone number
CREATE OR REPLACE MASKING POLICY mask_phone
AS (phone STRING) 
RETURNS STRING ->
  CASE 
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN') THEN phone
    ELSE CONCAT('XXXXXX', RIGHT(phone, 4))
  END;

-- Mask email
CREATE OR REPLACE MASKING POLICY mask_email
AS (email STRING)
RETURNS STRING ->
  CASE 
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN') THEN email
    ELSE CONCAT(LEFT(email, 2),'*****',SUBSTR(email, POSITION('@' IN email)))
  END;

-- Apply masking
ALTER TABLE CURATED_LAYER.CLEAN_PATIENTS MODIFY COLUMN PHONE SET MASKING POLICY MASK_PHONE;
ALTER TABLE CURATED_LAYER.CLEAN_PATIENTS MODIFY COLUMN EMAIL SET MASKING POLICY GOVERNANCE_LAYER.MASK_EMAIL;

