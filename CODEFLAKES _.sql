-- STREAMS & TASKS (Handled by Akash)
-- ================================================

-- Track changes
CREATE OR REPLACE STREAM APPT_STREAM ON TABLE STAGE_LAYER.APPOINTMENTS_RAW;
CREATE OR REPLACE STREAM BILL_STREAM ON TABLE STAGE_LAYER.BILLING_RAW;

-- Incremental load task
CREATE OR REPLACE TASK LOAD_APPT_TASK
WAREHOUSE = COMPUTE_WH
SCHEDULE = '1 MINUTE'
AS
MERGE INTO CURATED_LAYER.FACT_APPOINTMENT T
USING APPT_STREAM S
ON T.APPT_ID = S.APPT_ID
WHEN MATCHED THEN UPDATE SET STATUS = S.STATUS
WHEN NOT MATCHED THEN INSERT VALUES (
    S.APPT_ID, S.APPT_DATE, S.PATIENT_ID, S.DOCTOR_ID, S.STATUS
);

